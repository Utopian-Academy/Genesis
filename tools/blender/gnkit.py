def join_group(objs, name, origin=(0, 0, 0)):
    """Join these objects into one named part whose origin is `origin`: the
    pivot a part turns about (a moving head's yoke pans, its head tilts)."""
    bpy.ops.object.select_all(action="DESELECT")
    for o in objs:
        o.select_set(True)
    bpy.context.view_layer.objects.active = objs[0]
    if len(objs) > 1:
        bpy.ops.object.join()
    obj = bpy.context.active_object
    obj.name = name
    obj.data.name = name
    bpy.context.scene.cursor.location = origin
    bpy.ops.object.origin_set(type="ORIGIN_CURSOR")
    bpy.context.scene.cursor.location = (0, 0, 0)
    return obj


def parent(child, parent_obj):
    child.parent = parent_obj
    child.matrix_parent_inverse = parent_obj.matrix_world.inverted()


def made_since(before):
    """The objects created since `before` (a set of objects)."""
    return [o for o in bpy.data.objects if o not in before]


def lathe(name, profile, mat, segments=40, centre=(0, 0, 0), axis="Z", caps=True):
    """Turn a profile, points (radius, height) from the axis outwards, round
    the axis: lens barrels, bezels, domes, drums, knobs. Along Z by default,
    or X / Y for parts that point sideways. An end of the profile that stops
    short of the axis is closed with a flat cap unless caps=False (a ring, a
    tyre, anything open in the middle)."""
    bm = bmesh.new()
    rings = []
    for i in range(segments):
        a = 2 * math.pi * i / segments
        ring = []
        for r, h in profile:
            co = Vector((r * math.cos(a), r * math.sin(a), h))
            if axis == "Y":
                co = Vector((co.x, co.z, -co.y))
            elif axis == "X":
                co = Vector((co.z, co.x, co.y))
            ring.append(bm.verts.new(Vector(centre) + co))
        rings.append(ring)
    for i in range(segments):
        a, b = rings[i], rings[(i + 1) % segments]
        for k in range(len(profile) - 1):
            bm.faces.new((a[k], b[k], b[k + 1], a[k + 1]))
    # Close the ends where the profile does not reach the axis.
    for k in (0, len(profile) - 1) if caps else ():
        if profile[k][0] > 1e-6:
            bm.faces.new([rings[i][k] for i in range(segments)])
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-6)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    data = bpy.data.meshes.new(name)
    bm.to_mesh(data)
    bm.free()
    obj = bpy.data.objects.new(name, data)
    bpy.context.collection.objects.link(obj)
    bpy.context.view_layer.objects.active = obj
    return _finish(obj, name, mat)


def stadium(name, width, height, radius, thickness, base, mat, axis="X"):
    """A flat plate with a round top, `thickness` thick across X: a yoke arm.
    base is the centre of its bottom edge; the round end's centre is
    `height` above it."""
    x, y, z = base
    pts = [(y + radius, z), (y + radius, z + height)]
    for k in range(1, 12):
        a = math.pi * k / 12
        pts.append((y + radius * math.cos(a), z + height + radius * math.sin(a)))
    pts += [(y - radius, z + height), (y - radius, z)]
    return prism(name, pts, thickness, mat, x=x)


def screen_material(image, strength=1.3):
    """A screen showing one of the kit's pictures (tools/make_screens.py),
    lit from within. Keeps its own texture coordinates."""
    name = "Screen " + image
    mat = bpy.data.materials.get(name)
    if mat:
        return mat
    path = os.path.join(KIT_TEXTURES, image + ".png")
    if not os.path.exists(path):
        return material(name, (0.02, 0.03, 0.05), 0.15, emission=(0.12, 0.2, 0.35), strength=1.5)
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    mat["gn_keep_uv"] = True
    nt = mat.node_tree
    bsdf = nt.nodes["Principled BSDF"]
    tex = nt.nodes.new("ShaderNodeTexImage")
    tex.image = bpy.data.images.load(path, check_existing=True)
    nt.links.new(tex.outputs["Color"], bsdf.inputs["Base Color"])
    nt.links.new(tex.outputs["Color"], bsdf.inputs["Emission Color"])
    bsdf.inputs["Emission Strength"].default_value = strength
    bsdf.inputs["Roughness"].default_value = 0.12
    mat.diffuse_color = (0.1, 0.12, 0.16, 1.0)
    return mat


def picture(name, w, h, centre, mat, facing="+Y"):
    """A flat w x h picture (a screen's glass) centred at `centre`, showing
    its image the right way up to someone looking at it: facing "+Y" or
    "-Y" (standing up) or "up" (lying flat, read from +Y)."""
    bpy.ops.mesh.primitive_plane_add(size=1, location=(0, 0, 0))
    obj = bpy.context.active_object
    m = Matrix.Diagonal((w, h, 1, 1))
    if facing == "+Y":
        m = Matrix.Rotation(math.pi, 4, "Z") @ Matrix.Rotation(math.pi / 2, 4, "X") @ m
    elif facing == "-Y":
        m = Matrix.Rotation(math.pi / 2, 4, "X") @ m
    else:
        m = Matrix.Rotation(math.pi, 4, "Z") @ m
    obj.data.transform(Matrix.Translation(centre) @ m)
    return _finish(obj, name, mat)


def _catmull(p0, p1, p2, p3, t):
    t2, t3 = t * t, t * t * t
    return 0.5 * ((2 * p1) + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2 + (-p0 + 3 * p1 - 3 * p2 + p3) * t3)


def loft(name, stations, mat, ring=24, steps=4, caps=(True, True), up=(0, 0, 1), turn=1):
    """Sweep a cross-section through stations: each station is (centre,
    half_width, half_height[, roundness]). Between stations everything is
    eased on a smooth curve, so a handful of stations make an animal's body,
    a leg, a hull or a fuselage. Roundness 2 is an ellipse; higher is
    squarer (a cow's barrel, a hull's topsides). Sections stand square to the
    path; `up` says which way their height points (Z, or Y for a vertical
    path such as a leg)."""
    pts = [Vector(s[0]) for s in stations]
    vals = [Vector((s[1], s[2], s[3] if len(s) > 3 else 2.0)) for s in stations]
    n = len(stations)
    dense = []
    for i in range(n - 1):
        p0, p1, p2, p3 = pts[max(i - 1, 0)], pts[i], pts[i + 1], pts[min(i + 2, n - 1)]
        v0, v1, v2, v3 = vals[max(i - 1, 0)], vals[i], vals[i + 1], vals[min(i + 2, n - 1)]
        for k in range(steps):
            t = k / steps
            dense.append((_catmull(p0, p1, p2, p3, t), _catmull(v0, v1, v2, v3, t)))
    dense.append((pts[-1], vals[-1]))
    upv = Vector(up)
    bm = bmesh.new()
    rings = []
    # `turn` widens the stretch of path each section takes its direction
    # from: where the path bends sharply (a neck rising from a chest), wide
    # sections would otherwise swing round and fold into their neighbours.
    for i, (c, v) in enumerate(dense):
        a = dense[max(i - turn, 0)][0]
        b = dense[min(i + turn, len(dense) - 1)][0]
        tangent = (b - a).normalized() if (b - a).length > 1e-9 else Vector((0, 1, 0))
        side = tangent.cross(upv)
        if side.length < 1e-6:
            side = tangent.cross(Vector((0, 1, 0)))
        side.normalize()
        vert = side.cross(tangent).normalized()
        hw, hh, e = max(v.x, 1e-4), max(v.y, 1e-4), max(v.z, 0.5)
        ring_verts = []
        for k in range(ring):
            ang = 2 * math.pi * k / ring
            cx, sy = math.cos(ang), math.sin(ang)
            x = hw * math.copysign(abs(cx) ** (2.0 / e), cx)
            y = hh * math.copysign(abs(sy) ** (2.0 / e), sy)
            ring_verts.append(bm.verts.new(c + side * x + vert * y))
        rings.append(ring_verts)
    for i in range(len(rings) - 1):
        for k in range(ring):
            j = (k + 1) % ring
            bm.faces.new((rings[i][k], rings[i][j], rings[i + 1][j], rings[i + 1][k]))
    if caps[0]:
        bm.faces.new(list(reversed(rings[0])))
    if caps[1]:
        bm.faces.new(rings[-1])
    # Built winding inwards throughout; turn every face out. (recalc guesses,
    # and on a long thin shape such as a tail boom it guesses inside out.)
    bmesh.ops.reverse_faces(bm, faces=bm.faces[:])
    data = bpy.data.meshes.new(name)
    bm.to_mesh(data)
    bm.free()
    obj = bpy.data.objects.new(name, data)
    bpy.context.collection.objects.link(obj)
    bpy.context.view_layer.objects.active = obj
    return _finish(obj, name, mat)


def subdivide(obj, levels=2):
    bpy.context.view_layer.objects.active = obj
    mod = obj.modifiers.new("Subdivision", "SUBSURF")
    mod.levels = levels
    mod.render_levels = levels
    bpy.ops.object.modifier_apply(modifier=mod.name)
    return obj


def coat_material(name, roughness=0.8, sheen=0.0):
    """A material whose colour is painted per vertex (paint_vertices), for
    animal coats and patterned surfaces."""
    mat = bpy.data.materials.get(name)
    if mat:
        return mat
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nt = mat.node_tree
    bsdf = nt.nodes["Principled BSDF"]
    attr = nt.nodes.new("ShaderNodeVertexColor")
    attr.layer_name = "Col"
    nt.links.new(attr.outputs["Color"], bsdf.inputs["Base Color"])
    bsdf.inputs["Roughness"].default_value = roughness
    if sheen and "Sheen Weight" in bsdf.inputs:
        bsdf.inputs["Sheen Weight"].default_value = sheen
    mat.diffuse_color = (0.5, 0.4, 0.3, 1.0)
    return mat


def paint_vertices(obj, colour_at):
    """Colours every vertex by colour_at(position, normal) -> (r, g, b),
    into the "Col" attribute coat_material reads."""
    mesh = obj.data
    attr = mesh.color_attributes.get("Col") or mesh.color_attributes.new("Col", "FLOAT_COLOR", "POINT")
    # Colours are given as they look (sRGB); the attribute stores linear.
    lin = lambda c: c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4  # noqa: E731
    for i, v in enumerate(mesh.vertices):
        r, g, b = colour_at(obj.matrix_world @ v.co, v.normal)
        attr.data[i].color = (lin(r), lin(g), lin(b), 1.0)


def sweep_sections(name, sections, mat, cap_first=True, cap_last=False, close_top=True):
    """Bridge a run of cross-sections, each a list of points with the same
    count, open at the top (first and last point are the two gunwales, say).
    close_top decks it over, gunwale to gunwale; the first section can be
    capped flat (a transom)."""
    bm = bmesh.new()
    rings = [[bm.verts.new(Vector(p)) for p in sec] for sec in sections]
    n = len(sections[0])
    for i in range(len(rings) - 1):
        for k in range(n - 1):
            a, b, c, d = rings[i][k], rings[i][k + 1], rings[i + 1][k + 1], rings[i + 1][k]
            if len({a, b, c, d}) == 4:
                bm.faces.new((a, b, c, d))
        if close_top:
            a, b, c, d = rings[i][n - 1], rings[i][0], rings[i + 1][0], rings[i + 1][n - 1]
            if len({a, b, c, d}) == 4:
                bm.faces.new((a, b, c, d))
    # Sections run starboard gunwale, keel, port gunwale, so the sides face
    # out as built; the end caps are wound to face out too. Open hulls have
    # no inside for recalc to find, so nothing here guesses.
    if cap_first and len(set(rings[0])) > 2:
        bm.faces.new(list(reversed(rings[0])))
    if cap_last and len(set(rings[-1])) > 2:
        bm.faces.new(rings[-1])
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-5)
    data = bpy.data.meshes.new(name)
    bm.to_mesh(data)
    bm.free()
    obj = bpy.data.objects.new(name, data)
    bpy.context.collection.objects.link(obj)
    bpy.context.view_layer.objects.active = obj
    return _finish(obj, name, mat)


def material_by_face(obj, rule, mats):
    """Gives each face a material by rule(centre, normal) -> index into mats
    (antifouling below the waterline, a stripe above it, white topsides)."""
    for m in mats:
        if m.name not in [x.name for x in obj.data.materials if x]:
            obj.data.materials.append(m)
    index = {m.name: i for i, m in enumerate(obj.data.materials) if m}
    for f in obj.data.polygons:
        f.material_index = index[mats[rule(obj.matrix_world @ f.center, f.normal)].name]
