# How big one repeat of each surface is, in metres.
KIT_TILE = {"grille": 0.07, "powder_black": 0.35, "powder_white": 0.35, "powder_grey": 0.35, "plastic_black": 0.6,
            "alu_brushed": 0.5, "alu_satin": 0.5, "chrome": 1.0, "rubber": 0.3, "deck": 1.0,
            "fabric_black": 0.25, "fabric_white": 0.25}


def kit_material(surface, name=None, metallic=None, roughness_scale=1.0):
    """A PBR material from one of the kit's scanned surfaces
    (tools/fetch_kit_textures.py), tiled at its real size. Falls back to a
    flat colour if the textures have not been fetched."""
    name = name or surface.replace("_", " ").capitalize()
    mat = bpy.data.materials.get(name)
    if mat:
        return mat
    if surface == "chrome":
        # A scanned chrome carries its studio's reflections in its colour
        # map and reads mottled; true chrome is plain and mirror-bright.
        return material(name, (0.92, 0.92, 0.94), 0.04, 1.0)
    colour = os.path.join(KIT_TEXTURES, surface + "_color.jpg")
    if not os.path.exists(colour):
        return material(name, (0.05, 0.05, 0.05), 0.6)
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    mat["gn_surface"] = surface
    nt = mat.node_tree
    bsdf = nt.nodes["Principled BSDF"]
    coords = nt.nodes.new("ShaderNodeTexCoord")
    mapping = nt.nodes.new("ShaderNodeMapping")
    s = 1.0 / KIT_TILE.get(surface, 0.5)
    mapping.inputs["Scale"].default_value = (s, s, s)
    nt.links.new(coords.outputs["UV"], mapping.inputs["Vector"])

    def image(kind, colour_data):
        path = os.path.join(KIT_TEXTURES, "%s_%s.jpg" % (surface, kind))
        if not os.path.exists(path):
            return None
        node = nt.nodes.new("ShaderNodeTexImage")
        node.image = bpy.data.images.load(path, check_existing=True)
        node.image.colorspace_settings.name = "sRGB" if colour_data else "Non-Color"
        nt.links.new(mapping.outputs["Vector"], node.inputs["Vector"])
        return node

    nt.links.new(image("color", True).outputs["Color"], bsdf.inputs["Base Color"])
    rough = image("roughness", False)
    if rough:
        nt.links.new(rough.outputs["Color"], bsdf.inputs["Roughness"])
    metal = image("metalness", False)
    if metal and metallic is None:
        nt.links.new(metal.outputs["Color"], bsdf.inputs["Metallic"])
    else:
        bsdf.inputs["Metallic"].default_value = metallic or 0.0
    normal = image("normal", False)
    if normal:
        nm = nt.nodes.new("ShaderNodeNormalMap")
        nt.links.new(normal.outputs["Color"], nm.inputs["Color"])
        nt.links.new(nm.outputs["Normal"], bsdf.inputs["Normal"])
    mat.diffuse_color = (0.05, 0.05, 0.05, 1.0)
    return mat


def prism(name, profile, width, mat, x=0.0):
    """Extrude a side profile, points (y, z) in the YZ plane, `width` along X
    centred on x. The shape of speaker cabinets, wedges, console desks."""
    bm = bmesh.new()
    left = [bm.verts.new((x - width / 2, y, z)) for y, z in profile]
    right = [bm.verts.new((x + width / 2, y, z)) for y, z in profile]
    n = len(profile)
    bm.faces.new(left[::-1])
    bm.faces.new(right)
    for i in range(n):
        j = (i + 1) % n
        bm.faces.new((left[i], left[j], right[j], right[i]))
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    data = bpy.data.meshes.new(name)
    bm.to_mesh(data)
    bm.free()
    obj = bpy.data.objects.new(name, data)
    bpy.context.collection.objects.link(obj)
    bpy.context.view_layer.objects.active = obj
    return _finish(obj, name, mat)


def bevel(obj, width=0.008, segments=2):
    bpy.context.view_layer.objects.active = obj
    mod = obj.modifiers.new("Bevel", "BEVEL")
    mod.width = width
    mod.segments = segments
    mod.limit_method = "ANGLE"
    bpy.ops.object.modifier_apply(modifier=mod.name)
    return obj


def grid(name, count_x, count_y, size, gap, origin, mat, depth=0.01, axis="Z"):
    """A grid of little boxes: faders, buttons, keys, LEDs, vents."""
    out = []
    ox, oy, oz = origin
    for i in range(count_x):
        for j in range(count_y):
            if axis == "Z":
                base = (ox + i * (size[0] + gap), oy + j * (size[1] + gap), oz)
                out.append(box(name, (size[0], size[1], depth), base, mat))
            else:
                base = (ox + i * (size[0] + gap), oy, oz + j * (size[1] + gap))
                out.append(box(name, (size[0], depth, size[1]), base, mat))
    return out


def rotate_about(objs, axis, deg, pivot):
    m = Matrix.Translation(pivot) @ Matrix.Rotation(math.radians(deg), 4, axis) @ Matrix.Translation(-Vector(pivot))
    for o in objs:
        o.data.transform(m)


