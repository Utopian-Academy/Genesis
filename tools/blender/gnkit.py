"""Shared helpers for Genesis's Blender asset generators.

Every generator in tools/blender/ builds its models from primitives and
exports them as GLB with a CC0 licence sidecar, so every asset is ours to
license. Blender is Z-up and the glTF exporter converts to Godot's Y-up.

Conventions every asset follows:
  - origin at ground level, centred on the footprint, so placement can drop
    it straight onto a surface;
  - the front faces Blender +Y, which is Godot -Z: the direction look_at()
    points, so "face the stage" is one call. For people and for gear
    someone operates (consoles, decks) the front is the way they look;
  - metres, real-world sizes.

A trap: box() and friends apply their transforms, so a part's origin is the
world origin, not its own centre. Setting rotation or scale on a part
afterwards turns it about the world origin; use rotate_about() with an
explicit pivot, or build at the origin and move last.
"""

import json
import math
import os

import bmesh
import bpy
from mathutils import Matrix, Vector

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ASSETS = os.path.join(ROOT, "genesis_assets")


def license_for(script):
    return {
        "source": "Generated by tools/blender/%s" % script,
        "author": "Utopian Academy",
        "license": "CC0-1.0",
        "attribution": "None required",
    }


def reset():
    bpy.ops.wm.read_factory_settings(use_empty=True)


def material(name, color, roughness=0.8, metallic=0.0, alpha=1.0, emission=None, strength=1.0):
    mat = bpy.data.materials.get(name)
    if mat:
        return mat
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes["Principled BSDF"]
    bsdf.inputs["Base Color"].default_value = (*color, 1.0)
    bsdf.inputs["Roughness"].default_value = roughness
    bsdf.inputs["Metallic"].default_value = metallic
    bsdf.inputs["Alpha"].default_value = alpha
    if emission:
        bsdf.inputs["Emission Color"].default_value = (*emission, 1.0)
        bsdf.inputs["Emission Strength"].default_value = strength
    if alpha < 1.0:
        # The glTF exporter reads this to write alphaMode BLEND.
        mat.surface_render_method = "BLENDED"
    mat.diffuse_color = (*color, 1.0)
    return mat


def _finish(obj, name, mat):
    obj.name = name
    if mat:
        obj.data.materials.append(mat)
    return obj


def box(name, size, base, mat, bevel=0.0):
    """An axis-aligned box given by its full size and the centre of its base."""
    sx, sy, sz = size
    x, y, z = base
    bpy.ops.mesh.primitive_cube_add(size=1, location=(x, y, z + sz / 2))
    obj = bpy.context.active_object
    obj.scale = (sx, sy, sz)
    bpy.ops.object.transform_apply(scale=True)
    if bevel > 0:
        mod = obj.modifiers.new("Bevel", "BEVEL")
        mod.width = bevel
        mod.segments = 2
        bpy.ops.object.modifier_apply(modifier=mod.name)
    return _finish(obj, name, mat)


def cylinder(name, radius, depth, centre, mat, axis="Z", verts=16, radius2=None):
    """A cylinder (or cone, with radius2) centred on `centre` along an axis."""
    if radius2 is None:
        bpy.ops.mesh.primitive_cylinder_add(vertices=verts, radius=radius, depth=depth, location=centre)
    else:
        bpy.ops.mesh.primitive_cone_add(vertices=verts, radius1=radius, radius2=radius2, depth=depth, location=centre)
    obj = bpy.context.active_object
    if axis == "X":
        obj.rotation_euler = (0, math.pi / 2, 0)
    elif axis == "Y":
        obj.rotation_euler = (math.pi / 2, 0, 0)
    bpy.ops.object.transform_apply(rotation=True)
    return _finish(obj, name, mat)


def sphere(name, radius, centre, mat, scale=(1, 1, 1), segments=16):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=segments, ring_count=segments // 2, radius=radius, location=centre)
    obj = bpy.context.active_object
    obj.scale = scale
    bpy.ops.object.transform_apply(scale=True)
    bpy.ops.object.shade_smooth()
    return _finish(obj, name, mat)


def tube(name, points, radius, mat, verts=8):
    """A round bar along a polyline: pipes, rails, cables, handles."""
    curve = bpy.data.curves.new(name, "CURVE")
    curve.dimensions = "3D"
    curve.bevel_depth = radius
    curve.bevel_resolution = max(1, verts // 4 - 1)
    spline = curve.splines.new("POLY")
    spline.points.add(len(points) - 1)
    for p, co in zip(spline.points, points):
        p.co = (*co, 1.0)
    obj = bpy.data.objects.new(name, curve)
    bpy.context.collection.objects.link(obj)
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    bpy.ops.object.convert(target="MESH")
    obj = bpy.context.active_object
    return _finish(obj, name, mat)


def smooth(obj, angle=35):
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    bpy.ops.object.shade_auto_smooth(angle=math.radians(angle))


def join_all(name):
    bpy.ops.object.select_all(action="SELECT")
    meshes = [o for o in bpy.context.selected_objects if o.type == "MESH"]
    bpy.context.view_layer.objects.active = meshes[0]
    bpy.ops.object.join()
    obj = bpy.context.active_object
    obj.name = name
    obj.data.name = name
    # The origin goes at the world origin, which every builder treats as ground level.
    bpy.context.scene.cursor.location = (0, 0, 0)
    bpy.ops.object.origin_set(type="ORIGIN_CURSOR")
    # Rounded edges shade round, flat faces stay crisp.
    bpy.ops.object.shade_auto_smooth(angle=math.radians(40))
    return obj


def frame(name, w, h, base, depth, border, mat):
    """A rectangular bezel, `w` by `h` outside, `border` wide, standing proud
    of the plane y = base[1] by `depth`: round a grille, a screen, a panel."""
    x, y, z = base
    parts = [box(name, (w, depth, border), (x, y, z), mat),
             box(name, (w, depth, border), (x, y, z + h - border), mat),
             box(name, (border, depth, h - 2 * border), (x - w / 2 + border / 2, y, z + border), mat),
             box(name, (border, depth, h - 2 * border), (x + w / 2 - border / 2, y, z + border), mat)]
    return parts


def side_handle(x, y, z, w, h, side, recess_mat, bar_mat, depth=0.03):
    """A recessed carry handle in a side panel at x (side +1 or -1 says which
    way the panel faces): a dark pocket with a bar across it."""
    box("HandlePocket", (0.004, w, h), (x + side * 0.001, y, z), recess_mat)
    tube("HandleBar", [(x + side * 0.004, y - w * 0.38, z + h * 0.72), (x - side * depth * 0.4, y - w * 0.3, z + h * 0.72),
                       (x - side * depth * 0.4, y + w * 0.3, z + h * 0.72), (x + side * 0.004, y + w * 0.38, z + h * 0.72)],
         0.009, bar_mat)


def triangles(obj):
    deps = bpy.context.evaluated_depsgraph_get()
    mesh = obj.evaluated_get(deps).to_mesh()
    n = sum(len(p.vertices) - 2 for p in mesh.polygons)
    obj.evaluated_get(deps).to_mesh_clear()
    return n


def box_uv(obj):
    """Texture coordinates in metres, projected from whichever axis each face
    faces most: a tiled material is then the same real size on every part
    and every model. Faces whose material says gn_keep_uv (screens showing
    a picture) keep their own."""
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    uv = bm.loops.layers.uv.verify()
    keep = {i for i, m in enumerate(obj.data.materials) if m and m.get("gn_keep_uv")}
    for f in bm.faces:
        if f.material_index in keep:
            continue
        n = f.normal
        ax = max(range(3), key=lambda i: abs(n[i]))
        for loop in f.loops:
            co = loop.vert.co
            loop[uv].uv = (co.y, co.z) if ax == 0 else ((co.x, co.z) if ax == 1 else (co.x, co.y))
    bm.to_mesh(obj.data)
    bm.free()


def export(category, name, script, extra=None):
    """Writes the scene as genesis_assets/<category>/<name>.gltf, its
    textures shared in genesis_assets/kit_textures, with a licence sidecar."""
    # GN_ASSETS_OUT sends a trial build somewhere other than the library.
    folder = os.path.join(os.environ.get("GN_ASSETS_OUT", ASSETS), category)
    os.makedirs(folder, exist_ok=True)
    for o in bpy.data.objects:
        if o.type == "MESH":
            box_uv(o)
    for old in (name + ".glb", name + ".glb.import"):
        if os.path.exists(os.path.join(folder, old)):
            os.remove(os.path.join(folder, old))
    path = os.path.join(folder, name + ".gltf")
    bpy.ops.export_scene.gltf(filepath=path, export_format="GLTF_SEPARATE", export_texture_dir="../kit_textures",
                              export_apply=True, export_image_format="AUTO")
    info = license_for(script)
    used = sorted({m["gn_surface"] for m in bpy.data.materials if m.get("gn_surface")})
    if used:
        info["surfaces"] = {k: KIT_LICENCES.get(k, {}).get("source", "") for k in used}
        info["license_note"] = "Model CC0 (Utopian Academy); surface textures CC0 from ambientCG."
    if extra:
        info.update(extra)
    with open(os.path.join(folder, name + ".license.json"), "w") as f:
        json.dump(info, f, indent=2)
        f.write("\n")
    print("wrote", os.path.relpath(path, ROOT))
    return path


