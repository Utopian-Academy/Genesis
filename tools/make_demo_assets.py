# The house: two storeys, a lot of glass. The
# shape that architectural renders are usually of, and it has to show off sun,
# shadow and reflection.
# ---------------------------------------------------------------------------
def build_house():
    reset()
    concrete = material("Concrete", (0.72, 0.71, 0.68), 0.85)
    plaster = material("Plaster", (0.93, 0.92, 0.89), 0.9)
    wood = material("Wood", (0.42, 0.26, 0.15), 0.7)
    glass = material("Glass", (0.55, 0.65, 0.7), 0.05, 0.0, 0.3)
    frame = material("Frame", (0.08, 0.08, 0.09), 0.4, 0.8)

    # Plinth and terrace.
    box("Plinth", (16, 12, 0.3), (0, 0, 0), concrete)
    box("Terrace", (12, 3, 0.3), (0, -7.5, 0), concrete)

    # Ground floor: a plaster box with a fully glazed south face.
    g_w, g_d, g_h = 12, 8, 3.2
    box("GroundBack", (g_w, 0.3, g_h), (0, g_d / 2 - 0.15, 0.3), plaster)
    box("GroundLeft", (0.3, g_d, g_h), (-g_w / 2 + 0.15, 0, 0.3), plaster)
    box("GroundRight", (0.3, g_d, g_h), (g_w / 2 - 0.15, 0, 0.3), plaster)
    box("GroundGlass", (g_w - 0.6, 0.05, g_h), (0, -g_d / 2 + 0.2, 0.3), glass)
    for i in range(5):
        x = -g_w / 2 + 0.3 + i * (g_w - 0.6) / 4
        box("Mullion%d" % i, (0.08, 0.12, g_h), (x, -g_d / 2 + 0.2, 0.3), frame)
    box("Slab1", (g_w + 0.4, g_d + 0.4, 0.35), (0, 0, 0.3 + g_h), concrete)

    # Upper floor: wood-clad, square over the ground floor.
    u_w, u_d, u_h = 12, 8, 3.0
    ux, uz = 0.0, 0.3 + g_h + 0.35
    box("UpperBack", (u_w, 0.3, u_h), (ux, u_d / 2 - 0.15, uz), wood)
    box("UpperLeft", (0.3, u_d, u_h), (ux - u_w / 2 + 0.15, 0, uz), wood)
    box("UpperRight", (0.3, u_d, u_h), (ux + u_w / 2 - 0.15, 0, uz), wood)
    box("UpperFrontSolid", (u_w * 0.4, 0.3, u_h), (ux + u_w * 0.3, -u_d / 2 + 0.15, uz), wood)
    box("UpperGlass", (u_w * 0.6 - 0.3, 0.05, u_h - 0.6), (ux - u_w * 0.2, -u_d / 2 + 0.2, uz + 0.3), glass)
    box("UpperSill", (u_w * 0.6, 0.35, 0.3), (ux - u_w * 0.2, -u_d / 2 + 0.2, uz), frame)
    box("Roof", (u_w + 0.6, u_d + 0.6, 0.3), (ux, 0, uz + u_h), concrete)

    # Something inside so the glass reads as glass, not a hole.
    box("InteriorWall", (0.2, 5, g_h), (1.5, 0.5, 0.3), plaster)
    box("Counter", (3, 0.8, 0.9), (-3, 1.5, 0.3), wood)

    join_all("DemoHouse")
    export("architecture", "demo_house")


