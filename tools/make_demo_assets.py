"""Build Genesis's demo assets in Blender and export them as GLB.

Everything here is generated from primitives, so every asset is ours to
license. Run headless:

    blender --background --factory-startup --python tools/make_demo_assets.py

Blender is Z-up; the glTF exporter converts to Godot's Y-up. Every asset has
its origin at ground level so placement can drop it straight onto a surface.
"""

import json
import math
import os
import random

import bpy
import bmesh

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
ASSETS = os.path.join(ROOT, "genesis_assets")
LICENSE = {
    "source": "Generated by tools/make_demo_assets.py",
    "author": "Utopian Academy",
    "license": "CC0-1.0",
    "attribution": "None required",
}


def reset():
    bpy.ops.wm.read_factory_settings(use_empty=True)


def material(name, color, roughness=0.8, metallic=0.0, alpha=1.0):
    mat = bpy.data.materials.get(name) or bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes["Principled BSDF"]
    bsdf.inputs["Base Color"].default_value = (*color, 1.0)
    bsdf.inputs["Roughness"].default_value = roughness
    bsdf.inputs["Metallic"].default_value = metallic
    bsdf.inputs["Alpha"].default_value = alpha
    if alpha < 1.0:
        # The glTF exporter reads this to write alphaMode BLEND.
        mat.surface_render_method = "BLENDED"
    return mat


def box(name, size, location, mat):
    """An axis-aligned box given by its full size and the centre of its base."""
    sx, sy, sz = size
    x, y, z = location
    bpy.ops.mesh.primitive_cube_add(size=1, location=(x, y, z + sz / 2))
    obj = bpy.context.active_object
    obj.name = name
    obj.scale = (sx, sy, sz)
    bpy.ops.object.transform_apply(scale=True)
    obj.data.materials.append(mat)
    return obj


def join_all(name):
    bpy.ops.object.select_all(action="SELECT")
    bpy.context.view_layer.objects.active = bpy.context.selected_objects[0]
    bpy.ops.object.join()
    obj = bpy.context.active_object
    obj.name = name
    obj.data.name = name
    # The origin goes at the world origin, which every builder treats as ground level.
    bpy.context.scene.cursor.location = (0, 0, 0)
    bpy.ops.object.origin_set(type="ORIGIN_CURSOR")
    return obj


def export(category, name):
    folder = os.path.join(ASSETS, category)
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, name + ".glb")
    bpy.ops.export_scene.gltf(filepath=path, export_format="GLB", export_apply=True)
    with open(os.path.join(folder, name + ".license.json"), "w") as f:
        json.dump(LICENSE, f, indent=2)
        f.write("\n")
    print("wrote", os.path.relpath(path, ROOT))


