# Vegetation: low-poly and flat-shaded on purpose. These are placeholders that
# read well at a distance; they are not pretending to be photoreal trees.
# ---------------------------------------------------------------------------
def lumpy_sphere(name, radius, location, mat, seed):
    rng = random.Random(seed)
    bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=2, radius=radius, location=location)
    obj = bpy.context.active_object
    obj.name = name
    mesh = bmesh.new()
    mesh.from_mesh(obj.data)
    for v in mesh.verts:
        v.co *= 1.0 + rng.uniform(-0.18, 0.18)
    mesh.to_mesh(obj.data)
    mesh.free()
    obj.data.materials.append(mat)
    return obj


def trunk(height, radius, bark):
    bpy.ops.mesh.primitive_cone_add(vertices=8, radius1=radius, radius2=radius * 0.6,
                                    depth=height, location=(0, 0, height / 2))
    bpy.context.active_object.data.materials.append(bark)


def build_tree(name, seed, height, crown, leaf_color):
    reset()
    rng = random.Random(seed)
    bark = material("Bark", (0.25, 0.18, 0.12), 0.95)
    leaves = material("Leaves", leaf_color, 0.8)
    trunk(height * 0.6, 0.18 * height / 6, bark)
    lumpy_sphere("Crown", crown, (0, 0, height * 0.62), leaves, seed)
    for i in range(4):
        a = i * math.pi / 2 + rng.uniform(-0.4, 0.4)
        r = crown * 0.6
        lumpy_sphere("Crown%d" % i, crown * rng.uniform(0.55, 0.75),
                     (math.cos(a) * r, math.sin(a) * r, height * rng.uniform(0.5, 0.7)),
                     leaves, seed + i + 1)
    join_all(name)
    export("trees", name)


def build_shrub():
    reset()
    leaves = material("ShrubLeaves", (0.16, 0.3, 0.1), 0.85)
    rng = random.Random(7)
    for i in range(5):
        a = i * 2 * math.pi / 5
        lumpy_sphere("Lobe%d" % i, rng.uniform(0.35, 0.5),
                     (math.cos(a) * 0.35, math.sin(a) * 0.35, 0.35), leaves, 70 + i)
    join_all("shrub_round")
    export("plants", "shrub_round")


def build_grass():
    """A tuft of crossed blades. Scattered by the thousand, so it stays cheap."""
    reset()
    blade = material("Grass", (0.24, 0.42, 0.12), 0.9)
    rng = random.Random(11)
    mesh = bmesh.new()
    for i in range(9):
        a = rng.uniform(0, math.pi)
        h = rng.uniform(0.25, 0.45)
        w = 0.035
        lean = rng.uniform(-0.08, 0.08)
        dx, dy = math.cos(a) * w, math.sin(a) * w
        ox, oy = rng.uniform(-0.08, 0.08), rng.uniform(-0.08, 0.08)
        v1 = mesh.verts.new((ox - dx, oy - dy, 0))
        v2 = mesh.verts.new((ox + dx, oy + dy, 0))
        v3 = mesh.verts.new((ox + lean, oy + lean, h))
        mesh.faces.new((v1, v2, v3))
    data = bpy.data.meshes.new("grass_tuft")
    mesh.to_mesh(data)
    mesh.free()
    data.materials.append(blade)
    obj = bpy.data.objects.new("grass_tuft", data)
    bpy.context.collection.objects.link(obj)
    export("grass", "grass_tuft")


build_house()
build_tree("tree_round", 1, 7.0, 2.2, (0.18, 0.34, 0.12))
build_tree("tree_tall", 2, 10.0, 1.7, (0.14, 0.28, 0.1))
build_shrub()
build_grass()
